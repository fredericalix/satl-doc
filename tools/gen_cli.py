#!/usr/bin/env python3.12
"""Generate the SatL CLI reference from the binaries' own ``--help`` output.

The only source of truth is the binary: this walks ``satl <path...> --help``
recursively, parses clap's output, and writes one Markdown page per top-level
verb under ``docs/reference/cli/`` (plus ``index.md`` and ``satld.md``).

Why a parser and not ``clap_mangen``/``clap_complete``: adding a generator to
SatL would mean modifying SatL, and the docs repo is deliberately separate.
Parsing is safe here because clap's help output is *strictly positional* —
SatL sets no ``wrap_help``, so the output is byte-identical whatever
``COLUMNS`` says, and every field lives at a fixed indent.

The layout clap emits, and everything this parser leans on:

  * section headers at indent 0: ``Usage:``/``Arguments:``/``Options:``/``Commands:``
  * an entry starts at indent 2 (short flag, positional, subcommand) or
    indent 6 (long-only option, where the ``-x, `` column is blank)
  * an entry's help body is at indent 10, in the "long" template clap picks
    when any argument has a long help or documented possible values
  * in the "short" template the help sits on the entry line itself, after a
    run of two or more spaces

The one trap: in the long template clap emits **whitespace-only lines inside
an entry**, between the help text and the ``[env: ...]``/``[default: ...]``
tail (``--host`` is exactly that shape). Anything that splits entries on blank
lines mis-parses it. So entries are split on *indent*, never on blankness.
"""

from __future__ import annotations

import argparse
import dataclasses
import fnmatch
import re
import subprocess
import sys
from pathlib import Path

try:
    import yaml
except ImportError:  # pragma: no cover - environment problem, not a bug
    sys.exit("gen_cli: PyYAML is missing. Run `make install-deps`.")

BANNER = "<!-- Generated by make gen. Do not edit. -->"

# `Usage:` carries its payload on the same line; the others are bare headers.
USAGE_RE = re.compile(r"^Usage:\s*(.+)$")
HEADER_RE = re.compile(r"^(Arguments|Options|Commands):\s*$")
# Entries start at indent 2 or 6 and never deeper; bodies start at indent >= 7.
ENTRY_RE = re.compile(r"^ {2,6}(?=\S)")
# Trailing clap metadata: `[env: X=]`, `[default: y]`, `[possible values: a, b]`,
# `[alias: cluster]`. Peeled off the tail of a short-template description.
META_TAIL_RE = re.compile(
    r"\s*\[(env|default|possible values|alias(?:es)?|short alias(?:es)?):\s*([^\]]*)\]\s*$"
)
META_LINE_RE = re.compile(
    r"^\[(env|default|possible values|alias(?:es)?|short alias(?:es)?):\s*([^\]]*)\]$"
)
ALIAS_RE = re.compile(r"\s*\[alias(?:es)?:\s*([^\]]+)\]\s*$")
SHORT_RE = re.compile(r"^-([^-,\s])")
LONG_RE = re.compile(r"--([A-Za-z0-9][A-Za-z0-9-]*)")


# --------------------------------------------------------------------------- #
# model
# --------------------------------------------------------------------------- #


@dataclasses.dataclass
class Entry:
    """One row of an ``Arguments:`` or ``Options:`` section."""

    spec: str  # `-p, --publish <PORT>` or `<IMAGE>`
    help: str  # the prose, newlines preserved
    env: str | None = None
    default: str | None = None
    values: list[str] = dataclasses.field(default_factory=list)
    value_help: list[tuple[str, str]] = dataclasses.field(default_factory=list)

    @property
    def long(self) -> str | None:
        m = LONG_RE.search(self.spec)
        return f"--{m.group(1)}" if m else None

    @property
    def short(self) -> str | None:
        m = SHORT_RE.match(self.spec)
        return f"-{m.group(1)}" if m else None

    @property
    def key(self) -> str:
        """Stable identity for set operations: the long flag, else the spec."""
        return self.long or self.spec


@dataclasses.dataclass
class SubCommand:
    name: str
    summary: str
    aliases: list[str] = dataclasses.field(default_factory=list)


@dataclasses.dataclass
class Help:
    """A parsed ``--help`` page."""

    path: list[str]  # ["service", "create"] — the path actually invoked
    about: str
    usage: str
    arguments: list[Entry] = dataclasses.field(default_factory=list)
    options: list[Entry] = dataclasses.field(default_factory=list)
    commands: list[SubCommand] = dataclasses.field(default_factory=list)
    aliases: list[str] = dataclasses.field(default_factory=list)
    children: list["Help"] = dataclasses.field(default_factory=list)

    @property
    def canonical(self) -> list[str]:
        """The path clap itself prints in ``Usage:``.

        ``satl cluster --help`` prints ``Usage: satl swarm ...``: the canonical
        spelling is what keys the visited set, so an alias never produces a
        second page.
        """
        return usage_path(self.usage)

    @property
    def subcommand_required(self) -> bool:
        """``<COMMAND>`` means the bare verb is an error; ``[COMMAND]`` means it runs."""
        return "<COMMAND>" in self.usage


# --------------------------------------------------------------------------- #
# parsing
# --------------------------------------------------------------------------- #


def usage_path(usage: str) -> list[str]:
    """Command path out of a usage line, stopping at the first placeholder."""
    tokens = usage.split()[1:]  # drop the binary name
    path: list[str] = []
    for token in tokens:
        if not re.fullmatch(r"[a-z][a-z0-9-]*", token):
            break
        path.append(token)
    return path


def split_entries(body: list[str]) -> list[list[str]]:
    """Split a section body into entries, keyed on indent alone.

    Blank and whitespace-only lines belong to the entry they sit in — clap puts
    them *inside* one, so treating them as separators is the classic bug.
    """
    entries: list[list[str]] = []
    for line in body:
        if ENTRY_RE.match(line):
            entries.append([line])
        elif entries:
            entries[-1].append(line)
        # lines before the first entry are clap noise; there are none in practice
    return entries


def parse_entry(block: list[str]) -> Entry:
    """Turn one raw entry block into an :class:`Entry`."""
    head = block[0].strip()
    parts = re.split(r"\s{2,}", head, maxsplit=1)
    spec = parts[0]
    inline = parts[1].strip() if len(parts) > 1 else ""

    # Long template: the body sits on the following lines at indent 10.
    body = [line[10:] if len(line) > 10 else line.strip() for line in block[1:]]
    # Short template: a wrapped continuation would land in the description
    # column; SatL never wraps, but absorb it rather than drop it.
    if inline and body:
        body = [line.strip() for line in block[1:]]

    lines = ([inline] if inline else []) + body
    entry = Entry(spec=spec, help="")

    # `Possible values:` sub-block (long template only).
    value_help: list[tuple[str, str]] = []
    prose: list[str] = []
    in_values = False
    for raw in lines:
        line = raw.rstrip()
        if line.strip() == "Possible values:":
            in_values = True
            continue
        if in_values:
            m = re.match(r"^\s*-\s+([^:]+):\s*(.*)$", line)
            if m:
                value_help.append((m.group(1).strip(), m.group(2).strip()))
                continue
            if not line.strip():
                continue
            in_values = False
        prose.append(line)

    # Standalone metadata lines (long template).
    kept: list[str] = []
    for line in prose:
        m = META_LINE_RE.match(line.strip())
        if m:
            absorb_meta(entry, m.group(1), m.group(2))
        else:
            kept.append(line)

    text = "\n".join(kept).strip()
    # Trailing metadata (short template), peeled right to left.
    while True:
        m = META_TAIL_RE.search(text)
        if not m:
            break
        absorb_meta(entry, m.group(1), m.group(2))
        text = text[: m.start()].rstrip()

    entry.help = re.sub(r"\n{3,}", "\n\n", text).strip()
    entry.value_help = value_help
    if value_help and not entry.values:
        entry.values = [name for name, _ in value_help]
    return entry


def absorb_meta(entry: Entry, key: str, value: str) -> None:
    key = key.rstrip("es") if key.startswith("alias") else key
    value = value.strip()
    if key == "env":
        entry.env = value.rstrip("=") or None
    elif key == "default":
        entry.default = value
    elif key == "possible values":
        entry.values = [v.strip() for v in value.split(",") if v.strip()]


def parse_help(text: str, path: list[str]) -> Help:
    """Parse a full ``--help`` page."""
    lines = text.splitlines()

    about: list[str] = []
    usage = ""
    sections: dict[str, list[str]] = {}
    current: str | None = None

    for line in lines:
        m = USAGE_RE.match(line)
        if m:
            usage = m.group(1).strip()
            current = None
            continue
        m = HEADER_RE.match(line)
        if m:
            current = m.group(1)
            sections[current] = []
            continue
        if current:
            sections[current].append(line)
        elif not usage:
            about.append(line)

    help_obj = Help(
        path=path,
        about="\n".join(about).strip(),
        usage=usage,
    )

    for block in split_entries(sections.get("Arguments", [])):
        help_obj.arguments.append(parse_entry(block))
    for block in split_entries(sections.get("Options", [])):
        help_obj.options.append(parse_entry(block))

    for block in split_entries(sections.get("Commands", [])):
        head = block[0].strip()
        parts = re.split(r"\s{2,}", head, maxsplit=1)
        name = parts[0]
        summary = parts[1].strip() if len(parts) > 1 else ""
        # Continuations, if clap ever wraps a summary.
        for extra in block[1:]:
            if extra.strip():
                summary = f"{summary} {extra.strip()}".strip()
        aliases: list[str] = []
        m = ALIAS_RE.search(summary)
        if m:
            aliases = [a.strip() for a in m.group(1).split(",") if a.strip()]
            summary = summary[: m.start()].rstrip()
        help_obj.commands.append(SubCommand(name=name, summary=summary, aliases=aliases))

    return help_obj


# --------------------------------------------------------------------------- #
# harvesting
# --------------------------------------------------------------------------- #


def run_help(binary: Path, path: list[str]) -> str:
    """Capture ``--help`` (never ``-h``: only the long form has the long help)."""
    argv = [str(binary), *path, "--help"]
    proc = subprocess.run(argv, capture_output=True, text=True, check=False)
    if proc.returncode != 0:
        raise SystemExit(
            f"gen_cli: `{' '.join(argv)}` exited {proc.returncode}\n{proc.stderr.strip()}"
        )
    return proc.stdout


def harvest(binary: Path, path: list[str], visited: set[tuple[str, ...]]) -> Help | None:
    """Walk the command tree depth-first, once per canonical path."""
    node = parse_help(run_help(binary, path), path)
    key = tuple(node.canonical)
    if key in visited:
        return None
    visited.add(key)

    for sub in node.commands:
        # Never recurse into an alias: `satl cluster` is `satl swarm`, and
        # walking both would emit the page twice under two names.
        child = harvest(binary, [*node.canonical, sub.name], visited)
        if child is not None:
            child.aliases = sub.aliases
            node.children.append(child)
    return node


