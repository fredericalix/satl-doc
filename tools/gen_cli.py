@dataclasses.dataclass
class Overlay:
    globals: list[str]
    groups: list[dict]
    diffs: list[dict]
    deny_flags: list[str]

    @classmethod
    def load(cls, path: Path) -> "Overlay":
        data = yaml.safe_load(path.read_text()) or {}
        return cls(
            globals=data.get("globals", []),
            groups=data.get("groups", []),
            diffs=data.get("diff", []),
            deny_flags=data.get("deny_flags", []),
        )

    def group_for(self, path: list[str]) -> dict | None:
        for group in self.groups:
            if any(list(p) == path for p in group.get("applies_to", [])):
                return group
        return None

    def groups_on_page(self, verb: str) -> list[dict]:
        return [g for g in self.groups if g.get("page") == verb]


def is_group_option(entry: Entry, group: dict) -> bool:
    name = entry.long or entry.spec
    return any(fnmatch.fnmatch(name, pat) for pat in group.get("match", []))


# --------------------------------------------------------------------------- #
# rendering
# --------------------------------------------------------------------------- #


def esc(text: str) -> str:
    """Make a string safe inside a Markdown table cell."""
    return text.replace("|", r"\|").replace("\n", "<br>")


def code(text: str) -> str:
    """A code span for prose, where a backtick span behaves."""
    return f"`{text}`".replace("|", r"\|")


def tcode(text: str) -> str:
    """A code span for a *table cell*, as raw HTML rather than backticks.

    Backticks cannot carry a pipe inside a table. python-markdown's tables
    extension splits the row on unescaped ``|`` before inline processing runs,
    and the ``\\|`` that survives that split is then inside a code span, where
    backslash escapes do not apply — so ``<worker|manager>`` renders literally
    as ``<worker\\|manager>``. Emitting ``<code>`` with a numeric entity keeps
    the pipe out of the splitter's way and out of the code span's reach at once.
    """
    escaped = (
        text.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace("|", "&#124;")
    )
    return f"<code>{escaped}</code>"


def anchor(path: list[str], prefix: str = "satl") -> str:
    return "-".join([prefix, *path])


def describe(entry: Entry) -> str:
    """The description cell: prose plus clap's metadata tail."""
    parts = [esc(entry.help) if entry.help else "—"]
    if entry.values and not entry.value_help:
        parts.append("Values: " + ", ".join(tcode(v) for v in entry.values))
    if entry.value_help:
        rendered = "; ".join(f"{tcode(n)} — {esc(d)}" for n, d in entry.value_help)
        parts.append(f"Values: {rendered}")
    if entry.default:
        parts.append(f"Default: {tcode(entry.default)}")
    if entry.env:
        parts.append(f"Environment: {tcode(entry.env)}")
    return "<br>".join(parts)


def table(title: str, header: str, entries: list[Entry], out: list[str]) -> None:
    if not entries:
        return
    if title:
        out.append(f"{title}\n")
    out.append(f"| {header} | Description |")
    out.append("| --- | --- |")
    for entry in entries:
        out.append(f"| {tcode(entry.spec)} | {describe(entry)} |")
    out.append("")


def visible_options(node: Help, overlay: Overlay) -> list[Entry]:
    """Everything but the global flags, which get one section per page."""
    return [e for e in node.options if (e.long or e.spec) not in overlay.globals]


def render_command(node: Help, overlay: Overlay, level: int, out: list[str]) -> None:
    """Render one command as a heading plus its sections."""
    full = " ".join(["satl", *node.canonical])
    out.append(f"{'#' * level} `{full}` {{ #{anchor(node.canonical)} }}\n")
    if node.about:
        out.append(f"{node.about}\n")
    if node.aliases:
        spelled = ", ".join(
            code(" ".join(["satl", *node.canonical[:-1], a])) for a in node.aliases
        )
        out.append(
            f'!!! note "Alias"\n\n'
            f"    {code(full)} is also spelled {spelled}. Both are the same command;"
            f" this reference documents the canonical spelling.\n"
        )
    out.append("```console\n$ " + " ".join(["satl", *node.usage.split()[1:]]) + "\n```\n")

    # `<COMMAND>` versus `[COMMAND]` in the usage line is the whole difference
    # between a pure namespace verb and one that also does something itself.
    # `satl ca` is the bracketed case: it prints the root CA on its own, and
    # carries real options of its own alongside a subcommand — hence a hybrid
    # page rather than a bare list of children.
    if node.children:
        if node.subcommand_required:
            out.append(
                f"{code(full)} is a group: it always takes one of the subcommands "
                f"below.\n"
            )
        else:
            out.append(
                f"{code(full)} is valid on its own — the subcommand is optional "
                f"(`[COMMAND]` in the usage line above). Its own options are listed "
                f"first, its subcommands after.\n"
            )

    table("**Arguments**", "Argument", node.arguments, out)

    group = overlay.group_for(node.canonical)
    options = visible_options(node, overlay)
    if group:
        grouped = [e for e in options if is_group_option(e, group)]
        options = [e for e in options if not is_group_option(e, group)]
    else:
        grouped = []

    table("**Options**", "Option", options, out)
    if grouped:
        out.append(
            f"{code(full)} also accepts the "
            f"[{group['title'].lower()} options](#{group['id']}) "
            f"({len(grouped)} flags), documented once below.\n"
        )
    if not node.children and not node.arguments and not options and not grouped:
        out.append("Takes no arguments or options of its own.\n")

    for child in node.children:
        render_command(child, overlay, level + 1, out)


def render_group(group: dict, sample: Help, overlay: Overlay, out: list[str]) -> None:
    """The shared-option section a ``#[command(flatten)]`` struct leaves no trace of."""
    out.append(f"## {group['title']} {{ #{group['id']} }}\n")
    if group.get("intro"):
        out.append(group["intro"].strip() + "\n")
    users = ", ".join(
        code("satl " + " ".join(p)) for p in group.get("applies_to", [])
    )
    out.append(f"Accepted by {users}, with identical meaning.\n")
    entries = [e for e in sample.options if is_group_option(e, group)]
    table("", "Option", entries, out)


def render_diff(diff: dict, tree: dict[tuple[str, ...], Help], overlay: Overlay,
                out: list[str]) -> None:
    """Set-difference two sibling commands: facts derived, judgement written."""
    left_path, right_path = list(diff["left"]), list(diff["right"])
    left, right = tree[tuple(left_path)], tree[tuple(right_path)]
    group = overlay.group_for(left_path) or overlay.group_for(right_path)

    def keys(node: Help) -> dict[str, Entry]:
        result: dict[str, Entry] = {}
        for entry in [*node.arguments, *visible_options(node, overlay)]:
            if group and is_group_option(entry, group):
                continue
            result[entry.key] = entry
        return result

    lk, rk = keys(left), keys(right)
    lname = "satl " + " ".join(left_path)
    rname = "satl " + " ".join(right_path)

    out.append(f"## {diff['title']} {{ #{diff['id']} }}\n")
    if diff.get("intro"):
        out.append(diff["intro"].strip() + "\n")

    shared = sorted(set(lk) & set(rk))
    only_left = sorted(set(lk) - set(rk))
    only_right = sorted(set(rk) - set(lk))

    out.append(
        f"Derived mechanically from the two commands' own `--help`, "
        f"with the {group['title'].lower() if group else 'shared'} options and the "
        f"global options excluded.\n"
    )
    out.append(f"| Accepted by | Options |")
    out.append("| --- | --- |")
    out.append(
        f"| both | {', '.join(tcode(k) for k in shared) if shared else '—'} |"
    )
    out.append(
        f"| {tcode(lname)} only | "
        f"{', '.join(tcode(k) for k in only_left) if only_left else '—'} |"
    )
    out.append(
        f"| {tcode(rname)} only | "
        f"{', '.join(tcode(k) for k in only_right) if only_right else '—'} |"
    )
    out.append("")

    pairs = diff.get("pairs", [])
    if pairs:
        out.append(
            "A set difference cannot see that two differently-named options do the "
            "same job. These pairings are asserted by hand in `overlay/cli.yml`:\n"
        )
        out.append(f"| {tcode(lname)} | {tcode(rname)} | Why they differ |")
        out.append("| --- | --- | --- |")
        for pair in pairs:
            out.append(
                f"| {tcode(pair['left'])} | {tcode(pair['right'])} | "
                f"{esc(pair.get('note', ''))} |"
            )
        out.append("")


def render_globals(root: Help, overlay: Overlay, out: list[str]) -> None:
    entries = [e for e in root.options if (e.long or e.spec) in overlay.globals]
    if not entries:
        return
    out.append("## Global options { #global-options }\n")
    out.append("Accepted by every `satl` command.\n")
    table("", "Option", entries, out)


def page_footer(version: str) -> str:
    return (
        f"\n---\n\n*Generated from `{version}` by `make gen`. Change it in the SatL "
        f"source or in `overlay/cli.yml`, never here.*\n"
    )


def page_header(version: str, stale: bool) -> list[str]:
    out = [BANNER, f"<!-- Source: {version} -->", ""]
    if stale:
        out += [
            '!!! danger "Generated from a stale binary"',
            "",
            "    This page was produced with `--allow-stale`: the `satl` binary it was",
            "    harvested from does not match the SatL source tree. Commands or flags",
            "    may be missing or wrong. Rebuild with `make gen-fresh`.",
            "",
        ]
    return out


