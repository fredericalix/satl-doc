def check_deny(nodes: list[Help], overlay: Overlay) -> None:
    """Tripwire: a hidden flag must never reach a page.

    clap already omits ``hide = true`` arguments from ``--help``, so harvesting
    excludes them for free — which is precisely why this needs asserting rather
    than assuming: the day someone documents one by hand, or clap changes its
    mind, the build should stop.
    """
    if not overlay.deny_flags:
        return
    found: list[str] = []
    for node in nodes:
        for entry in [*node.options, *node.arguments]:
            name = entry.long or entry.spec
            if any(fnmatch.fnmatch(name, pat) for pat in overlay.deny_flags):
                found.append(f"{' '.join(['satl', *node.canonical])}: {name}")
    if found:
        raise SystemExit(
            "gen_cli: deny_flags tripwire fired — these must never be documented:\n  "
            + "\n  ".join(found)
        )


def flatten(node: Help, acc: list[Help]) -> None:
    acc.append(node)
    for child in node.children:
        flatten(child, acc)


def write(path: Path, lines: list[str]) -> None:
    path.write_text("\n".join(lines).rstrip() + "\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--satl", required=True, type=Path)
    parser.add_argument("--satld", required=True, type=Path)
    parser.add_argument("--out", required=True, type=Path)
    parser.add_argument("--overlay", required=True, type=Path)
    parser.add_argument(
        "--stale",
        action="store_true",
        help="mark every page as harvested from a binary that failed the drift check",
    )
    args = parser.parse_args()

    for binary in (args.satl, args.satld):
        if not binary.is_file():
            return fail(f"gen_cli: no such binary: {binary}\nRun `make gen-fresh`.")

    overlay = Overlay.load(args.overlay)
    version = subprocess.run(
        [str(args.satl), "--version"], capture_output=True, text=True, check=True
    ).stdout.strip()

    root = harvest(args.satl, [], set())
    assert root is not None
    nodes: list[Help] = []
    flatten(root, nodes)
    check_deny(nodes, overlay)
    tree = {tuple(n.canonical): n for n in nodes}

    args.out.mkdir(parents=True, exist_ok=True)
    for old in args.out.glob("*.md"):
        old.unlink()

    # One page per top-level verb.
    for verb in root.children:
        name = verb.canonical[0]
        out = page_header(version, args.stale)
        render_command(verb, overlay, 1, out)
        for group in overlay.groups_on_page(name):
            sample = tree[tuple(group["applies_to"][0])]
            render_group(group, sample, overlay, out)
        for diff in overlay.diffs:
            if list(diff["left"])[0] == name:
                render_diff(diff, tree, overlay, out)
        render_globals(root, overlay, out)
        out.append(page_footer(version))
        write(args.out / f"{name}.md", out)

    # Index: every verb, in the binary's own order.
    out = page_header(version, args.stale)
    out.append("# `satl` command reference\n")
    out.append(root.about + "\n" if root.about else "")
    out.append("```console\n$ " + " ".join(["satl", *root.usage.split()[1:]]) + "\n```\n")
    out.append("| Command | Description |")
    out.append("| --- | --- |")
    for verb in root.children:
        name = verb.canonical[0]
        summary = next(
            (c.summary for c in root.commands if c.name == name), verb.about
        )
        alias = (
            f"<br>Alias: {', '.join(tcode(a) for a in verb.aliases)}"
            if verb.aliases
            else ""
        )
        out.append(f"| [`satl {name}`]({name}.md) | {esc(summary)}{alias} |")
    out.append("")
    out.append(f"The daemon has [its own page](satld.md).\n")
    render_globals(root, overlay, out)
    out.append(page_footer(version))
    write(args.out / "index.md", out)

    # The daemon, through the same parser.
    satld_version = subprocess.run(
        [str(args.satld), "--version"], capture_output=True, text=True, check=True
    ).stdout.strip()
    daemon = parse_help(run_help(args.satld, []), [])
    out = page_header(satld_version, args.stale)
    out.append("# `satld` { #satld }\n")
    if daemon.about:
        out.append(daemon.about + "\n")
    out.append(f"```console\n$ {daemon.usage}\n```\n")
    table("**Options**", "Option", daemon.options, out)
    out.append(
        "`satld` is configured from a file, not from flags: see "
        "[`satld.toml`](../satld-toml.md).\n"
    )
    out.append(page_footer(satld_version))
    write(args.out / "satld.md", out)

    print(f"gen_cli: wrote {len(list(args.out.glob('*.md')))} pages to {args.out}")
    return 0


def fail(message: str) -> int:
    print(message, file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main())
